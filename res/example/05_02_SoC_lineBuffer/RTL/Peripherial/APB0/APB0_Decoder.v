//==============================================================================
//  APB0_Decoder.v  ——  APB0 窗口内的地址译码
//------------------------------------------------------------------------------
//  APB0 窗口:0xf8100000 ~ 0xf810FFFF,共 64 KB
//  SoC 送进来的 PADDR 已经是窗口内的字节偏移,所以这里只看 16 位。
//
//  地址分配(4 KB 一槽,槽号 = PADDR[15:12]):
//      槽 0        0x0000 - 0x0FFF      按键 KEY
//      槽 1        0x1000 - 0x1FFF      空闲(DDR 自检 CHECKER 已从系统摘除, 源文件保留)
//      槽 2        0x2000 - 0x2FFF      行缓冲器 lineBuffer
//      槽 3 ~ 15   0x3000 - 0xFFFF      加速器(留 52 KB)
//
//  加外设的做法:在上面照抄一段,填上自己的槽号,再到 APB0_Interconnect 里补三行回程选择即可
//==============================================================================

module APB0_Decoder (
    input  wire [15:0]  APB_0_PADDR,
    input  wire         APB_0_PSEL,

    output wire         PSEL_key,
    output wire         PSEL_lineBuffer
);

//------------------------------------------------------------------------------
// 按键 KEY
//------------------------------------------------------------------------------
//0x0000   KEY_DATA
//0x0004   KEY_IRQ_EN
//0x0008   KEY_ID
/*Insert KEY decoder code there*/
assign PSEL_key = APB_0_PSEL && (APB_0_PADDR[15:12] == 4'b0000);
/***********************************/

//------------------------------------------------------------------------------
// 槽 1: 空闲
//   原来这里是 DDR 自检 CHECKER(0x1000-0x1FFF)。它已整块从系统里摘掉
//   (AXI 主口和 APB 总线层都不再接, 省 LUT), 源文件仍留在 RTL 目录里。
//   ★ 现在访问 0x1000 段不会选中任何外设: 回程兜底给 PREADY=1 / PSLVERROR=1,
//     软件会读到错误响应 —— 不要再访问这个槽。
//------------------------------------------------------------------------------

//------------------------------------------------------------------------------
// 行缓冲器 lineBuffer
//------------------------------------------------------------------------------
//0x2000   LINEBUFFER_ID                RO
//0x2004   FRAMEA_BASE_ADDR_ACC         RW     完整帧·左半(加速器画的, 显示在读)
//0x2008   FRAMEA_BASE_ADDR_CPU         RW     完整帧·右半(CPU 画的, 显示在读)
//0x200C   FRAMEB_BASE_ADDR_ACC         RW     正在画·左半
//0x2010   FRAMEB_BASE_ADDR_CPU         RW     正在画·右半
//0x2014   FRAMEC_FULL_BASE_ADDR_ACC    RW     全屏模式·完整帧(加速器独占)
//0x2018   FRAMED_FULL_BASE_ADDR_ACC    RW     全屏模式·正在画
//0x201C   STATUS                       RW     {MODE,ENABLE}
//0x2020   FPS_ACC                      RO     加速器交帧计数
//0x2024   FPS_CPU                      RO     CPU 交帧计数
//0x2028   DONE_CPU                     RW1S   bit0: CPU 这半幅画完. 写1置位
//0x202C   DONE_ACC                     RW1S   bit0: ACC 这半幅画完. 写1置位(加速器也可硬件置位)
//
//  ★ DONE_CPU / DONE_ACC 都是 RW1S(写 1 置位, 写 0 不动):
//      置位: CPU 写 1 / 加速器硬件置位
//      清零: 只有 lineBuffer 在帧边界消费掉自己那一位时才清  ← 硬性要求, 软件不许清
//    两位互相独立: acc 快就 acc 先翻, cpu 没画完就一直读它上一帧的地址
//    两位同时为 1, 就是"下一次帧边界整帧一起换"的情形, 不需要额外逻辑
/*Insert lineBuffer decoder code there*/
assign PSEL_lineBuffer = APB_0_PSEL && (APB_0_PADDR[15:12] == 4'b0010);

endmodule
