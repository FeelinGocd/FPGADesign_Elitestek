//==============================================================================
//  APB0_Decoder.v  ——  APB0 窗口内的地址译码
//------------------------------------------------------------------------------
//  APB0 窗口:0xf8100000 ~ 0xf810FFFF,共 64 KB
//  SoC 送进来的 PADDR 已经是窗口内的字节偏移,所以这里只看 16 位。
//
//  地址分配(4 KB 一槽,槽号 = PADDR[15:12]):
//      槽 0        0x0000 - 0x0FFF      按键 KEY
//      槽 1 ~ 15   0x1000 - 0xFFFF      加速器(留 60 KB)
//
//  加外设的做法:在上面照抄一段,填上自己的槽号,再到 APB0_Interconnect 里补三行回程选择即可
//==============================================================================

module APB0_Decoder (
    input  wire [15:0]  APB_0_PADDR,
    input  wire         APB_0_PSEL,

    output wire         PSEL_key
);

//------------------------------------------------------------------------------
// 按键 KEY
//------------------------------------------------------------------------------
//0x0000   KEY_DATA
//0x0004   KEY_IRQ_EN
//0x0008   KEY_ID
/*Insert KEY decoder code there*/
assign PSEL_key = APB_0_PSEL && (APB_0_PADDR[15:12] == 4'b0000);
/***********************************/

endmodule
