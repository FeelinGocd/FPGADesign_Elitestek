/*******************************************************************************
*
* @file user_checker.c
*
* @brief 用户 APB "DDR 自检"外设驱动的实现。
*
* 对应 RTL:
*     RTL/Peripherial/APB0/APB0_Interconnect.v
*     RTL/Peripherial/APB0/APB0_Decoder.v            (槽 1 = PSEL_checker)
*     RTL/Peripherial/APB0/BRAM/APB0_DDR_checker.v   (总线层)
*     RTL/Peripherial/BRAM/DDR_checker.v             (功能层)
*
* 地址: APB0 窗口 0xf8100000, 译码到槽 1 (槽内偏移 0x1000 ~ 0x1FFF)
*
******************************************************************************/

#include "user_checker.h"
#include "bsp.h"            /* bsp_uDelay */
#include "io.h"             /* 带来 soc.h 里的 IO_APB_SLAVE_0_INPUT */

/*------------------------------------------------------------------------------
 * 基地址
 *
 *   APB Slave 0 的窗口基址由易灵思按 SoC 配置生成在 soc.h 里 (0xf8100000)。
 *   槽 1 的基址 = 窗口基址 + 0x1000 (和 RTL 的 APB0_Decoder.v 里
 *   "PADDR[15:12] == 4'b0001" 必须一致, 改一处就要改另一处)。
 *----------------------------------------------------------------------------*/
#ifdef IO_APB_SLAVE_0_INPUT
    #define CHECKER_BASE    (IO_APB_SLAVE_0_INPUT + 0x1000u)
#else
    #error "APB Slave 0 is disabled, please enable it in IP Manager!!!"
#endif

/*------------------------------------------------------------------------------
 * 寄存器映射
 *
 *   成员顺序 = 地址偏移顺序。一个字都不能改、不能删、不能插空位 ——
 *   结构体是靠偏移量访问硬件的, 顺序错了读写的就是别的寄存器。
 *
 *   槽内偏移    成员        读写    说明
 *   -------------------------------------------------------------------------
 *   0x00        ctrl        RW      bit0 = start, 写 1 启动, 硬件自动清
 *   0x04        status      RO      bit0=busy bit1=done bit2=pass bit[15:8]=errcode
 *   0x08        err_addr    RO      第一个不一致的字节地址
 *   0x0C        err_exp     RO      期望值(低 32 位)
 *   0x10        err_act     RO      实际值(低 32 位)
 *   0x14        test_id     RO      恒为 0x43484B30 ("CHK0" 的 ASCII)
 *
 *   volatile 不能省: 每次访问都必须真去总线, 不允许编译器缓存或合并。
 *
 *   !! 以后要在 0x18 之后加寄存器, 必须先补一个占位成员, 不能直接往后追加:
 *          volatile u32 reserved;      // 0x18 占位
 *          volatile u32 new_reg;       // 0x1C 新寄存器
 *----------------------------------------------------------------------------*/
typedef struct {
    volatile u32 ctrl;          /* 0x00  RW  bit0 = start */
    volatile u32 status;        /* 0x04  RO */
    volatile u32 err_addr;      /* 0x08  RO */
    volatile u32 err_exp;       /* 0x0C  RO */
    volatile u32 err_act;       /* 0x10  RO */
    volatile u32 test_id;       /* 0x14  RO */
} CHECKERType;

/* 把基地址当成 CHECKERType 结构体的首地址 */
#define CHECKER             ((CHECKERType *)CHECKER_BASE)

/* 轮询间隔(微秒) */
#define CHECKER_POLL_US     1000


/*==============================================================================
 * API 实现
 *============================================================================*/

/*******************************************************************************
*
* @brief 读外设 ID, 用来确认这个 APB 外设确实活着。
*
* @return 正常情况下恒为 CHECKER_ID_VALUE (0x43484B30)
*
******************************************************************************/
u32 checker_getId(void){
    return CHECKER->test_id;
}

/*******************************************************************************
*
* @brief 启动一次自检(不等结果)。
*
* @note CTRL.start 是"写 1 触发"型: RTL 收到后就自动清零,
*       所以这里直接写 1 就行, 不用手动清。
*
* @note 自检正在进行中时写 CTRL 会被 RTL 忽略(start 只在空闲/跑完时生效)。
*
******************************************************************************/
void checker_start(void){
    CHECKER->ctrl = 1u;
}

/*******************************************************************************
*
* @brief 自检是否正在跑。
*
******************************************************************************/
u32 checker_isBusy(void){
    return (CHECKER->status & CHECKER_ST_BUSY) ? 1u : 0u;
}

/*******************************************************************************
*
* @brief 自检是否跑完了。
*
******************************************************************************/
u32 checker_isDone(void){
    return (CHECKER->status & CHECKER_ST_DONE) ? 1u : 0u;
}

/*******************************************************************************
*
* @brief 自检是否通过。只有跑完才有意义。
*
******************************************************************************/
u32 checker_isPass(void){
    return (CHECKER->status & CHECKER_ST_PASS) ? 1u : 0u;
}

/*******************************************************************************
*
* @brief 读错误码。0 = 无错误。
*
******************************************************************************/
u32 checker_getErrCode(void){
    return CHECKER_ST_ERRCODE(CHECKER->status);
}

/*******************************************************************************
*
* @brief 读第一个不一致的字节地址。
*
******************************************************************************/
u32 checker_getErrAddr(void){
    return CHECKER->err_addr;
}

/*******************************************************************************
*
* @brief 读期望值(低 32 位)。
*
******************************************************************************/
u32 checker_getErrExp(void){
    return CHECKER->err_exp;
}

/*******************************************************************************
*
* @brief 读实际读回的值(低 32 位)。
*
******************************************************************************/
u32 checker_getErrAct(void){
    return CHECKER->err_act;
}

/*******************************************************************************
*
* @brief 启动一次自检, 并等它跑完。
*
* @param wait_ms 最长等待毫秒数。建议 500。
*
* @return 1 = 通过, 0 = 失败或等待超时。
*
******************************************************************************/
u32 checker_runOnce(u32 wait_ms){
    u32 tick = 0;

    checker_start();

    /* 轮询等 done。done 是粘滞的, 只要跑完就一定读得到, 不会漏 */
    while(!checker_isDone()){
        if(tick >= wait_ms)
            return 0u;                  /* 等待超时(不是自检失败, 结果未知) */
        bsp_uDelay(CHECKER_POLL_US);
        tick++;
    }

    return checker_isPass();
}
