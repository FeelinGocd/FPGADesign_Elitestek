/*******************************************************************************
*
* @file user_checker.h
*
* @brief 用户 APB "DDR 自检"外设 —— 对外 API。
*
* 实现: project/peripheral/APB0/checker/user_checker.c
* 对应 RTL:
*     RTL/Peripherial/APB0/BRAM/APB0_DDR_checker.v    (总线层: APB 解析 + 寄存器)
*     RTL/Peripherial/BRAM/DDR_checker.v              (功能层: 序列器 + 图案 + 比对)
*
* 地址: APB0 窗口 0xf8100000 的槽 1
*       CTRL     = 0xf8101000   STATUS   = 0xf8101004   ERR_ADDR = 0xf8101008
*       ERR_EXP  = 0xf810100C   ERR_ACT  = 0xf8101010   TEST_ID  = 0xf8101014
*
* 干什么:
*     FPGA 自己把一块图案从 BRAM 写进 DDR, 再原样读回来逐拍比对 ——
*     全程不占 CPU, CPU 只负责"按开始"和"看结果"。
*     这是 AXI Master 的第一道验证: 证明数据真的能进 DDR、真的能取回来。
*
******************************************************************************/

#pragma once

#include "type.h"

/*******************************************************************************
*
* @brief test_id 的期望值, "CHK0" 的 ASCII。
*        读 checker_getId() 拿到这个值, 就说明整条 APB 通路是通的。
*
******************************************************************************/
#define CHECKER_ID_VALUE        0x43484B30u

/*------------------------------------------------------------------------------
 * STATUS 寄存器位定义
 *----------------------------------------------------------------------------*/
#define CHECKER_ST_BUSY         0x00000001u     /* bit0 自检进行中 */
#define CHECKER_ST_DONE         0x00000002u     /* bit1 跑完了(粘滞到下次 start) */
#define CHECKER_ST_PASS         0x00000004u     /* bit2 跑完且没错 */
#define CHECKER_ST_ERRCODE(s)   (((s) >> 8) & 0xFFu)    /* bit[15:8] 错误码 */

/*------------------------------------------------------------------------------
 * errcode 取值(与 RTL 的 DDR_checker.v 一一对应)
 *----------------------------------------------------------------------------*/
#define CHECKER_ERR_NONE        0u      /* 无错误 */
#define CHECKER_ERR_MISMATCH    1u      /* 读回不一致 */
#define CHECKER_ERR_RESP        2u      /* 响应非 OKAY */
#define CHECKER_ERR_TIMEOUT     3u      /* 超时 —— 常见原因: DDR 还没校准完 */
#define CHECKER_ERR_PATTERN     4u      /* 图案未加载 —— .hex 路径不对 */

/*******************************************************************************
*
* @brief 读外设 ID, 用来确认这个 APB 外设确实活着。
*
* @return 正常情况下恒为 CHECKER_ID_VALUE (0x43484B30)
*
******************************************************************************/
u32  checker_getId(void);

/*******************************************************************************
*
* @brief 启动一次自检。
*
* @note 这是个"按下就返回"的函数, 不等结果。
*       要等结果请用 checker_runOnce(), 或者自己轮询 checker_isDone()。
*
* @note 需要等 DDR 校准完成才有意义:
*       RTL 里本模块的复位是 sys_rst & cal_done, 校准完成前一直处于复位,
*       此时写 CTRL 无效。
*
******************************************************************************/
void checker_start(void);

/*******************************************************************************
*
* @brief 自检是否正在跑。
*
* @return 1 = 正在跑, 0 = 空闲或已跑完
*
******************************************************************************/
u32  checker_isBusy(void);

/*******************************************************************************
*
* @brief 自检是否跑完了。
*
* @return 1 = 跑完(结果可以读了), 0 = 还没
*
******************************************************************************/
u32  checker_isDone(void);

/*******************************************************************************
*
* @brief 自检是否通过。只有跑完才有意义。
*
* @return 1 = 通过, 0 = 失败或还没跑完
*
******************************************************************************/
u32  checker_isPass(void);

/*******************************************************************************
*
* @brief 读错误码。
*
* @return 见上面的 CHECKER_ERR_* 定义。0 = 无错误。
*
******************************************************************************/
u32  checker_getErrCode(void);

/*******************************************************************************
*
* @brief 读第一个不一致的字节地址。只有 errcode = MISMATCH 时才有意义。
*
******************************************************************************/
u32  checker_getErrAddr(void);

/*******************************************************************************
*
* @brief 读期望值(低 32 位)。只有 errcode = MISMATCH 时才有意义。
*
******************************************************************************/
u32  checker_getErrExp(void);

/*******************************************************************************
*
* @brief 读实际读回的值(低 32 位)。只有 errcode = MISMATCH 时才有意义。
*
******************************************************************************/
u32  checker_getErrAct(void);

/*******************************************************************************
*
* @brief 启动一次自检, 并等它跑完。
*
* @param wait_ms 最长等待毫秒数。正常跑完只要 1ms 左右;
*               如果 DDR 没就绪, RTL 内部每条命令 10ms 超时, 32 条最坏约 320ms,
*               所以建议传 500。
*
* @return 1 = 通过, 0 = 失败或等待超时。
*         不管返回什么, 详细结果都留在寄存器里, 用 getErrCode/Addr/Exp/Act 去读。
*
* @note 刚上电就调用可能拿到 CHECKER_ERR_TIMEOUT —— 那是 DDR 还没校准完。
*       隔 200ms 重试一次即可(见 main.c 的用法)。
*
******************************************************************************/
u32  checker_runOnce(u32 wait_ms);
