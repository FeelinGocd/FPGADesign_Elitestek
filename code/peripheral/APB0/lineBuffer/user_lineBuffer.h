/*******************************************************************************
*
* @file user_lineBuffer.h
*
* @brief 用户 APB "显示通道 lineBuffer"外设 —— 对外 API。
*
* 实现: project/peripheral/APB0/lineBuffer/user_lineBuffer.c
* 对应 RTL:
*     RTL/Peripherial/APB0/APB0_Interconnect.v           (槽 1 译码, 里面例化总线层)
*     RTL/Peripherial/APB0/lineBuffer/APB0_lineBuffer.v  (总线层: APB 解析 + 寄存器)
*     RTL/Peripherial/LineBuffer/lineBuffer.v            (功能层: 整条显示通路)
*
* 地址: APB0 窗口 0xf8100000 的槽 1 (槽内偏移 0x1000 ~ 0x1FFF), 与 AXI 从口 S1 同号
*       0x1000 ID              RO    恒 0x4C423031
*       0x1004 FRAMEA_BASE_ACC RW    缓冲 A·左半(分屏时加速器画的)
*       0x1008 FRAMEA_BASE_CPU RW    缓冲 A·右半(分屏时 CPU 画的)
*       0x100C FRAMEB_BASE_ACC RW    缓冲 B·左半
*       0x1010 FRAMEB_BASE_CPU RW    缓冲 B·右半
*       0x1014 FRAMEC_FULL     RW    缓冲 C·全屏
*       0x1018 FRAMED_FULL     RW    缓冲 D·全屏
*       0x101C STATUS          RW    bit0 = ENABLE, bit1 = SPLIT(0 全屏 1 分屏)
*       0x1020 FPS_ACC         RO    加速器帧率
*       0x1024 FPS_CPU         RO    CPU 帧率
*       0x1028 DONE_CPU        RW1S  写 1 置位
*       0x102C DONE_ACC        RW1S  写 1 置位
*
* 干什么:
*     DDR 里放好几块帧缓存, FPGA 自己按行从 DDR 取数 -> 跨 100M/148.5M 双 bank 缓冲
*     -> 拆成 24bit 像素 -> 真 1080p60 TMDS 输出到 HDMI。
*     CPU 只管: 定基址 / 交帧(写 DONE) / 开使能 / 看帧率。
*
* 帧缓存格式(★ 软件最容易写错的地方):
*     1920 x 1080, 每像素 3 字节, 行距固定 5760 字节, 行间不许有 padding
*     ★ 一个像素的字节顺序是【B, G, R】—— 地址最低那个字节是"蓝"!
*       (RTL 依据: unpacker 把最早到的字节放在 pixel_data[7:0];
*                  TMDS 编码器把 [23:16] 当红, [15:8] 绿, [7:0] 蓝)
*     行优先: 行内左->右, 行间上->下。
*     红蓝反了、或者整体偏几列, 基本都是这里写错了。
*
* DONE 的规矩(和别的外设不一样, 注意):
*     置位: CPU 写 1 (W1S), 或加速器走硬件置位
*     清零: 【只有 handler 在帧边界翻页后自己清, 软件不许清】
*     写 DONE = "这一块画完了, 下一个帧边界切过去显示"
*     静态图不写 DONE: 不写就永远显示当前那一块, 不会翻页。
*
******************************************************************************/

#pragma once

#include "type.h"

/*******************************************************************************
*
* @brief ID 寄存器的期望值, "LB01" 的 ASCII。
*        读 lineBuffer_getId() 拿到这个值, 就说明整条 APB 通路是通的。
*
******************************************************************************/
#define LINEBUFFER_ID_VALUE     0x4C423031u

/*------------------------------------------------------------------------------
 * STATUS 寄存器位定义
 *----------------------------------------------------------------------------*/
#define LINEBUFFER_ST_ENABLE    0x00000001u     /* bit0 使能(不锁存, 写 0 立即停) */
#define LINEBUFFER_ST_SPLIT     0x00000002u     /* bit1 分屏(帧边界才生效) */

/*------------------------------------------------------------------------------
 * 帧缓存几何(和 RTL 里写死的 5760/1080 必须一致)
 *----------------------------------------------------------------------------*/
#define LINEBUFFER_WIDTH        1920u
#define LINEBUFFER_HEIGHT       1080u
#define LINEBUFFER_LINE_BYTES   5760u                                   /* 1920 * 3 */
#define LINEBUFFER_PIXEL_BYTES  3u
#define LINEBUFFER_FRAME_BYTES  (LINEBUFFER_LINE_BYTES * LINEBUFFER_HEIGHT)  /* 6220800 */
/* 分屏半幅: 每幅 960 列, 行距 2880 字节, 一块约 2.97MB */
#define LINEBUFFER_HALF_WIDTH       960u
#define LINEBUFFER_HALF_LINE_BYTES  2880u                               /* 960 * 3 */
#define LINEBUFFER_HALF_FRAME_BYTES (LINEBUFFER_HALF_LINE_BYTES * LINEBUFFER_HEIGHT)

/*******************************************************************************
*
* @brief 读外设 ID, 用来确认这个 APB 外设确实活着。
*
* @return 正常情况下恒为 LINEBUFFER_ID_VALUE (0x4C423031)
*
******************************************************************************/
u32  lineBuffer_getId(void);

/*******************************************************************************
*
* @brief 设置全屏模式的两块显示缓冲基址(C / D)。
*
* @param base_c 上电默认显示的那一块(C)
* @param base_d 画好了等切过去的那一块(D)
*
* @note 全屏模式(STATUS.SPLIT = 0)下, 显示用的就是 C/D 这一对;
*       A/B 那四个半幅基址用不到。
*
******************************************************************************/
void lineBuffer_setFullBase(u32 base_c, u32 base_d);

/*******************************************************************************
*
* @brief 设置分屏模式的两块显示缓冲基址(A / B), 每块都是"左半 + 右半"。
*
* @param a_acc  缓冲 A 左半(加速器画的)
* @param a_cpu  缓冲 A 右半(CPU 画的)
* @param b_acc  缓冲 B 左半
* @param b_cpu  缓冲 B 右半
*
******************************************************************************/
void lineBuffer_setSplitBase(u32 a_acc, u32 a_cpu, u32 b_acc, u32 b_cpu);

/*******************************************************************************
*
* @brief 开/关显示通道。
*
* @param en 1 = 开, 0 = 关
*
* @note ENABLE 不锁存: 写 0 立刻停取数。刚上电建议先 0, 把图灌完再开,
*       免得先看到半张图。
*
******************************************************************************/
void lineBuffer_enable(u32 en);

/*******************************************************************************
*
* @brief 请求切换全屏/分屏模式。
*
* @param split 0 = 全屏(一行取 1 段), 1 = 分屏(一行取左右 2 段)
*
* @note 模式在【帧边界】才生效, 一帧之内的取数几何永远一致(防撕裂)。
*       写 SPLIT 的那一拍, RTL 会把两个 DONE 一起丢掉(它们属于旧模式)。
*
******************************************************************************/
void lineBuffer_setSplit(u32 split);

/*******************************************************************************
*
* @brief 读当前 STATUS(bit0 = ENABLE, bit1 = SPLIT 待生效值)。
*
******************************************************************************/
u32  lineBuffer_getStatus(void);

/*******************************************************************************
*
* @brief 显示通道是否已使能。
*
******************************************************************************/
u32  lineBuffer_isEnabled(void);

/*******************************************************************************
*
* @brief 当前请求的模式是否为分屏。
*
******************************************************************************/
u32  lineBuffer_isSplit(void);

/*******************************************************************************
*
* @brief 读加速器侧帧率(handler 算好的, 单位: 帧/秒)。
*
* @note 没写 DONE 之前恒为 0 —— 帧率统计的是"交帧事件", 不是显示刷新率。
*
******************************************************************************/
u32  lineBuffer_getFpsAcc(void);

/*******************************************************************************
*
* @brief 读 CPU 侧帧率。
*
******************************************************************************/
u32  lineBuffer_getFpsCpu(void);

/*******************************************************************************
*
* @brief 交帧(加速器侧): 写 1 置位 DONE_ACC。
*
* @note 只是置位, 真正翻页发生在下一个帧边界; 翻完 handler 会自动清掉,
*       软件不要自己去清, 也不要去读回来判断(读回来只是当前是否还挂着)。
*
******************************************************************************/
void lineBuffer_doneAcc(void);

/*******************************************************************************
*
* @brief 交帧(CPU 侧): 写 1 置位 DONE_CPU。
*
******************************************************************************/
void lineBuffer_doneCpu(void);

/*******************************************************************************
*
* @brief 读 DONE_ACC 寄存器的当前值(1 = 还挂着, 0 = 已被 handler 在帧边界消费掉)。
*
* @note 排错用: 写完 lineBuffer_doneAcc() 立刻读回一次 ——
*       能分清"寄存器根本没写进去" 和 "写进去了但 handler 没消费"。
*
******************************************************************************/
u32  lineBuffer_getDoneAcc(void);

/*******************************************************************************
*
* @brief 往一块帧缓存里灌"上板验证图案": 第 0 行纯白, 其余行 B 固定、G 随行变、
*        R 随列变。
*
* @param base  帧缓存基址(必须是 5760 对齐的普通 DDR 地址)
* @param lines 灌几行(1 ~ 1080)。上板第一次建议只灌 16 行 ——
*              屏上最上面几行是图案、下面是花屏, 一眼就能判断地址/行距/
*              像素顺序对不对。
*
* @note 函数末尾会刷一次 data cache: 不刷的话 CPU 写的数据可能还压在 cache 里,
*       FPGA 从 DDR 读到的是旧内容(常见现象: 屏上是上一次的图或花屏)。
*
******************************************************************************/
void lineBuffer_fillTestPattern(u32 base, u32 lines);

/*******************************************************************************
*
* @brief 往一块帧缓存里灌 EBU 8 竖彩条(白/黄/青/绿/品红/红/蓝/黑, 每 240 列一条)。
*
* @param base  帧缓存基址
* @param lines 灌几行(1 ~ 1080)
*
* @note 彩条是判断"颜色对不对"最快的图案:
*       如果 RTL 的字节序被写成了 RGB(而不是 BGR), 彩条顺序会明显不对
*       (青和黄对调、红和蓝对调), 一眼就能看出来。
*
* @note 同样会刷 data cache。
*
******************************************************************************/
void lineBuffer_fillColorBars(u32 base, u32 lines);

/*******************************************************************************
*
* @brief 排错专用: 灌一幅"坐标标记"图案 —— 用来看清地址映射对不对。
*
*     整屏黑, 然后:
*       左上 120x120 = 红        右上 120x120 = 绿
*       左下 120x120 = 蓝        右下 120x120 = 白
*       第 0 行       = 白(行对齐标记)
*       x = 959/960   = 黄竖线(水平中线)
*       y = 539/540   = 洋红横线(垂直中线)
*
* @param base 帧缓存基址(整屏 1080 行)
*
* @note 屏上应该是"黑底 + 四个角块 + 十字线"。任何一项不对都能直接定位:
*       角块位置反了/镜像   -> 行内或行间映射反了
*       中线一侧内容折返    -> 数据在行中间被换掉了(取数/缓冲的问题)
*       出现竖直硬缝        -> 一行的后半截数据来源不对
*       整屏偏几列/几行     -> 基址或行距不对
*
******************************************************************************/
void lineBuffer_fillMarkerPattern(u32 base);

/*******************************************************************************
*
* @brief 把一块帧缓存灌成纯色(排错用: 用来"标记"某一块缓冲)。
*
* @param base  帧缓存基址
* @param lines 灌几行(1 ~ 1080)
* @param r/g/b 0~255
*
* @note 让 C 和 D 用完全不同的内容(比如 C = 坐标标记图案, D = 纯蓝),
*       屏上只要出现 D 的内容就说明翻页发生了, 一眼可判。
*
******************************************************************************/
void lineBuffer_fillSolid(u32 base, u32 lines, u8 r, u8 g, u8 b);

/*******************************************************************************
*
* @brief 往一块【半幅】缓冲里灌纯色(分屏用: 960 列, 行距 2880)。
*
* @param base  半幅缓冲基址(A·左半 / A·右半 / B·左半 / B·右半 各一块)
* @param lines 灌几行(1 ~ 1080)
* @param r/g/b 0~255
*
* @note 每行的第 0 列和最后一列(959)强制画成白色 —— 这两条白边正好夹出半幅的
*       边界。分屏时屏上应该看到: 左半两条白边 + 右半两条白边, 而左半的右白边
*       和右半的左白边**紧挨着**拼在屏幕正中。中缝位置不对(错开或重叠)一眼可见。
*
******************************************************************************/
void lineBuffer_fillHalf(u32 base, u32 lines, u8 r, u8 g, u8 b);

/*******************************************************************************
*
* @brief 排错专用: 灌"标尺"图案 —— 用来精确量出显示的水平/垂直映射。
*
*     黑底, 上面画:
*       竖线(4 像素宽, 全高), 位置 x = 0/256/512/768/1024/1280/1536/1792,
*       颜色依次 白/红/绿/蓝/黄/青/品红/橙
*       横线(4 行高, 全宽), 位置 y = 0/270/540/810/1077, 全部白色
*
* @param base 帧缓存基址(整屏 1080 行)
*
* @note 正确的话屏上应该是 8 根等间距的彩色竖线 + 5 根等间距的白横线。
*       - 竖线都**等间距**但整体偏了一段 -> 每行的取数相位偏了(平移)
*       - 竖线**间距不均匀**(被压缩/拉伸) -> 取数速率和像素时钟对不上
*       - 某一根线跑到屏幕另一边 -> 一行内容被循环移位了, 移位量 = 
*         (这根线的实际位置 - 它在 x=… 的标称位置), 可以精确读出来
*
******************************************************************************/
void lineBuffer_fillRulerPattern(u32 base);

/*******************************************************************************
*
* @brief 把帧缓存里的某个像素读回来(先刷 cache, 保证读的是 DDR 里的真实内容)。
*
* @param base 帧缓存基址
* @param x    列 0..1919
* @param y    行 0..1079
*
* @return 按 0xRRGGBB 拼好的值, 方便直接和屏上颜色对照。
*
* @note 这是"排错用"的读回: 它证明 DDR 里存的到底是什么。
*       屏上内容 = DDR 内容 + 显示通路的映射, 两个一对就能定位是谁的问题。
*
******************************************************************************/
u32  lineBuffer_readPixel(u32 base, u32 x, u32 y);
