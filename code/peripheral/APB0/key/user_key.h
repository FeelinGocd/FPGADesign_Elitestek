/*******************************************************************************
*
* @file user_key.h
*
* @brief 用户 APB 按键外设 —— 对外 API。
*
* 实现: code/peripheral/APB0/key/user_key.c（同步到工程后的路径为 peripheral/APB0/key/user_key.c）
* 对应 RTL: RTL/Peripherial/APB0/key/APB0_key.v
*
* 这个头文件只暴露函数, 不暴露寄存器结构体。
* 寄存器长什么样、怎么访问, 是实现细节, 调用方不需要知道。
*
* 地址: APB0 窗口 0xf8100000 的槽 0
*       KEY_DATA = 0xf8100000   KEY_IRQ_EN = 0xf8100004   KEY_ID = 0xf8100008
*
* 中断: 按键按下沿 -> key_irq -> SoC userInterruptA -> PLIC ID 16
*      (SYSTEM_PLIC_USER_INTERRUPT_A_INTERRUPT)
*
******************************************************************************/

#pragma once

#include "type.h"

/*******************************************************************************
*
* @brief key_id 的期望值, "KEY0" 的 ASCII。
*        读 key_getId() 拿到这个值, 就说明整条 APB 通路是通的。
*
******************************************************************************/
#define KEY_ID_VALUE        0x4B455930

/*******************************************************************************
*
* @brief 读按键状态。key_state 由 RTL 顶层按键模块维护, 松开自动清零。
*
* @return bit[3:0], 按下 = 1, 松开 = 0 (已消抖)
*
******************************************************************************/
u32  key_getData(void);

/*******************************************************************************
*
* @brief 读中断使能。
*
* @return bit[3:0] 当前的中断使能位
*
******************************************************************************/
u32  key_getIrqEn(void);

/*******************************************************************************
*
* @brief 写中断使能。bit[n]=1 允许第 n 个键的按下沿产生中断。
*
* @param mask bit[3:0] 使能位。想"按任意键都进中断"就传 0xF。
*
******************************************************************************/
void key_setIrqEn(u32 mask);

/*******************************************************************************
*
* @brief 读外设 ID, 用来确认这个 APB 外设确实活着。
*
* @return 正常情况下恒为 KEY_ID_VALUE (0x4B455930)
*
******************************************************************************/
u32  key_getId(void);

