/*******************************************************************************
*
* @file user_key.c
*
* @brief 用户 APB 按键外设驱动的实现。
*
* 对应 RTL:
*     RTL/Peripherial/APB0/APB0_Interconnect.v
*     RTL/Peripherial/APB0/APB0_Decoder.v
*     RTL/Peripherial/APB0/key/APB0_key.v
*     RTL/Peripherial/APB0/key/key.v
*
* 地址: APB0 窗口 0xf8100000, 译码到槽 0 (偏移 0x0000 ~ 0x0FFF)
*
******************************************************************************/

#include "user_key.h"
#include "io.h"             /* 带来 soc.h 里的 IO_APB_SLAVE_0_INPUT */

/*------------------------------------------------------------------------------
 * 基地址
 *
 *   APB Slave 0 的窗口基址由易灵思按 SoC 配置生成在 soc.h 里 (0xf8100000)。
 *   如果在 IP Manager 里没使能 APB Slave 0, 这个宏根本不存在, 直接编译报错
 *----------------------------------------------------------------------------*/
#ifdef IO_APB_SLAVE_0_INPUT
    #define KEY_BASE        IO_APB_SLAVE_0_INPUT
#else
    #error "APB Slave 0 is disabled, please enable it in IP Manager!!!"
#endif

/* 按键个数 */
#define KEY_NUM             4

/* bit[KEY_NUM-1:0] 的掩码 */
#define KEY_MASK            ((1u << KEY_NUM) - 1u)

/*------------------------------------------------------------------------------
 * 寄存器映射
 *
 *   成员顺序 = 地址偏移顺序。一个字都不能改、不能删、不能插空位 ——
 *   结构体是靠偏移量访问硬件的, 顺序错了读写的就是别的寄存器。
 *
 *   槽内偏移    成员              读写    说明
 *   -------------------------------------------------------------------------
 *   0x00        key_data          RO      消抖后的按键状态, bit[3:0], 按下 = 1
 *   0x04        key_irq_en        RW      按下沿中断使能, bit[3:0]
 *   0x08        key_id            RO      恒为 0x4B455930 ("KEY0" 的 ASCII)
 *
 *   volatile 不能省: 每次访问都必须真去总线, 不允许编译器缓存或合并。
 *
 *   !! 以后要在 0x0C 之后加寄存器, 必须先补一个占位成员, 不能直接往后追加:
 *          volatile u32 reserved;      // 0x0C 占位
 *          volatile u32 new_reg;       // 0x10 新寄存器
 *----------------------------------------------------------------------------*/
typedef struct {
    volatile u32 key_data;          /* 0x00  RO */
    volatile u32 key_irq_en;        /* 0x04  RW */
    volatile u32 key_id;            /* 0x08  RO */
} KEYType;

/* 把基地址当成 KEYType 结构体的首地址 */
#define KEY                 ((KEYType *)KEY_BASE)


/*==============================================================================
 * API 实现
 *============================================================================*/

/*******************************************************************************
*
* @brief 读按键状态。key_state 由 key.v 内部维护, 松开自动清零。
*
* @return bit[3:0], 按下 = 1, 松开 = 0 (已消抖)
*
******************************************************************************/
u32 key_getData(void){
    return KEY->key_data & KEY_MASK;
}

/*******************************************************************************
*
* @brief 读中断使能。
*
* @return bit[3:0] 当前的中断使能位
*
******************************************************************************/
u32 key_getIrqEn(void){
    return KEY->key_irq_en & KEY_MASK;
}

/*******************************************************************************
*
* @brief 写中断使能。bit[n]=1 允许第 n 个键的按下沿产生中断。
*
* @param mask bit[3:0] 使能位。想"按任意键都进中断"就传 0xF。
*
* @note 掩码在函数内部处理, 传 0xFFFF 也不会把无效位写进去。
*
******************************************************************************/
void key_setIrqEn(u32 mask){
    KEY->key_irq_en = mask & KEY_MASK;
}

/*******************************************************************************
*
* @brief 读外设 ID, 用来确认这个 APB 外设确实活着。
*
* @return 正常情况下恒为 KEY_ID_VALUE (0x4B455930)
*
******************************************************************************/
u32 key_getId(void){
    return KEY->key_id;
}
