//==============================================================================
//  asyn_rst_syn.v —— 异步复位、同步释放
//------------------------------------------------------------------------------
//  功能
//      把异步复位同步释放到目标时钟域（两级触发器打拍），
//      输出转成高有效。给像素域这种"复位要从别的域来、释放要同步"的场合用。
//==============================================================================
module asyn_rst_syn(
    input               clk,            //目的时钟域
    input               rst_n,        //异步复位 低有效
    
    output              syn_reset       //高有效
    );
    
//define reg
reg reset_1;
reg reset_2;

/*****************************************************/
/*                   main code                       */
/*****************************************************/

assign syn_reset = reset_2;

//对异步复位信号进行同步释放 并转换为高有效
always@(posedge clk or negedge rst_n) begin
    if(!rst_n) begin
        reset_1  <= 1'b1;
        reset_2  <= 1'b1;
    end
    else begin
        reset_1 <= 1'b0;
        reset_2 <= reset_1;
    end
end

endmodule